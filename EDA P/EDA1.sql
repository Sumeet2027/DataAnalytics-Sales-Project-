-- FIND TOTAL NO CUSTOMER BY COUNTRY
SELECT 
country,
	COUNT(customer_key)  AS TOTAL_CUSTOMER
	FROM dbo.dim_customers
	GROUP BY country
ORDER BY TOTAL_CUSTOMER DESC

-- FIND TOTAL CUSTOMER BY GENDER
SELECT 
gender,
	COUNT(customer_key)  AS TOTAL_CUSTOMER
	FROM dbo.dim_customers
	GROUP BY gender
ORDER BY TOTAL_CUSTOMER DESC

-- FIND TOTAL PRODUCT BY CATEGROY
