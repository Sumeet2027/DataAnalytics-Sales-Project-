category,
COUNT(product_key) AS TOTAL_PRDUCT
FROM dbo.dim_products
GROUP BY category
ORDER BY TOTAL_PRDUCT

-- AVG COST INI EACH CATEGORY
SELECT 
category,
AVG(cost) AS AVG_COST
FROM dbo.dim_products
GROUP BY category
ORDER BY AVG_COST DESC

-- WHAT IS THE TOTAL REVANUE GENRETED BY EACH CATEGORY
-- WHAT IS THE TOTAL REVENUE GENERATED BY EACH CATEGORY?

SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM dbo.fact_sales AS f
LEFT JOIN dbo.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

---- RANKING ANALYSICS ---------------------
-- WHICH 5 PRODUCTS GENERATE THE HIGHEST REVENUE?

SELECT TOP 5
    p.product_name,
    SUM(f.sales_amount) AS total_revenue
FROM dbo.fact_sales AS f
LEFT JOIN dbo.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC;

-- WHAT ARE THE  5 WORST PERFORMANCE IN TERMS OF SALES
-- WHAT ARE THE 5 WORST-PERFORMING PRODUCTS IN TERMS OF SALES?

SELECT TOP 5
    p.product_name,
    SUM(f.sales_amount) AS total_sales
FROM dbo.fact_sales AS f
LEFT JOIN dbo.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_sales ASC;

-- TOP 10 CUSTOMERS WHO GENERATED THE HIGHEST REVENUE

SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM dbo.fact_sales AS f
LEFT JOIN dbo.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;